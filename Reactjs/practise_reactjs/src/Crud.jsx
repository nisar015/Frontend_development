import { Component} from "react";
import './Crud.css'
class CRUD extends Component {
    constructor() {
        super()
        // this means the state is belong to CRUD component
        this.state = {
            users: [
                { fname: "nisar",lname: "achukatla",email: "nisar@gmail.com",Mobilenum: 1234567891},
                { fname: "mike",lname: "jackson",email: "jackson@gmail.com",Mobilenum: 1234567891},
                { fname: "john",lname: "carter",email: "carter@gmail.com",Mobilenum: 1234567891},
                { fname: "nikhil",lname: "kamath",email: "kamath@gmail.com",Mobilenum: 1234567891},
            ],
            newuser:
                {
                    fname: "",
                    lname: "",
                    email: "",
                    Mobilenum: ""
                }
        }
    }

    handledelete=(index)=>{
        // const newuser=this.state.users.filter((use)=>{
        //     return use.email != user.email
        // })
        // we cannot directly delete or update the state
        // 1.create a copy of the state
        // 2.delete or update the state
        // 3.reassign value back to the state
        const newuser=[...this.state.users]
        console.log(newuser);
        newuser.splice(index,1)
        this.setState({users:newuser})
        // updates the current state i.e users
    }
    handleinputchange = (event) => {
        console.log(event.target.value);
        const inputval = {...this.state.newuser}
        inputval[event.target.name] = event.target.value;
        this.setState({ newuser: inputval })
    }
    handlecreateuser=()=>{
        console.log(this.state.newuser);
        const createuse=[...this.state.users]
        createuse.push(this.state.newuser)
        this.setState({users:createuse})
        this.clearform()
    }
    clearform=()=>{
        const newuser={
            fname:"",
            lname:"",
            email:"",
            Mobilenum:""
        }
        this.setState({newuser:newuser})
    }
    render() {
        const {fname,lname,email,Mobilenum}=this.state.newuser
        return <div>
            <form>
                <label htmlFor="">fname</label>
                <input type="text" name="fname" onChange={(event) => { this.handleinputchange(event) }} value={fname} /> <br />
                <label htmlFor="">lname</label>
                <input type="text" name="lname" onChange={(event) => { this.handleinputchange(event) }} value={lname} /> <br />
                <label htmlFor="">email</label>
                <input type="text" name="email" onChange={(event) => { this.handleinputchange(event) }} value={email} /> <br />
                <label htmlFor="">Mobilenum</label>
                <input type="text" name="Mobilenum" onChange={(event) => { this.handleinputchange(event) }} value={Mobilenum} /> <br />
                <button type="button" onClick={this.handlecreateuser}>Create User</button>
            </form>
            <table border={1}>
                <thead>
                    <tr>
                        <th>fname</th>
                        <th>lname</th>
                        <th>email</th>
                        <th>mobile num</th>
                        <th>edit</th>
                        <th>delete</th>
                    </tr>
                </thead>
                <tbody>
                    {this.state.users.map((user,index)=>{
                        //because of dynamically generated by using map loop browser cant identify the variation in the tr's so we declare uniqe keys
                        return <tr key={index}>   
                            <td>{user.fname}</td>
                            <td>{user.lname}</td>
                            <td>{user.email}</td>
                            <td>{user.Mobilenum}</td>
                            <td><button onClick={()=>{this.handledelete(index)}}>delete</button></td>

                        </tr>
                    })}
                </tbody>
            </table>
        </div>
    }
}
export default CRUD